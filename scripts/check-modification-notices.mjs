#!/usr/bin/env node
/**
 * Apache-2.0 §4(b) modification notices for the HeoPress fork of LumiBase.
 *
 * Every upstream file the HeoPress project has changed must say so:
 * - files that can hold a comment carry the NOTICE_MARKER line in the file;
 * - files that cannot (JSON, Markdown, lockfiles, binaries, ...) are listed in
 *   LICENSES/HEOPRESS-MODIFIED-FILES.txt.
 * Copyright lines present in the upstream version of a modified file must
 * still be present.
 *
 * Usage:
 *   node scripts/check-modification-notices.mjs          # check, exit 1 on problems
 *   node scripts/check-modification-notices.mjs --fix    # add notices, rewrite the list
 *   options: --root <dir> --base <commit>
 *
 * The comparison is upstream base -> working tree, so it also covers
 * uncommitted changes. The base commit must be present in the clone (CI needs
 * full history).
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const UPSTREAM_BASE = '93936ef0a4ce215e436beffe0cde6828fc8ff76e';
export const NOTICE_MARKER = 'Modified by the HeoPress project; based on LumiBase (Apache-2.0). See NOTICE.';
export const MODIFIED_LIST = 'LICENSES/HEOPRESS-MODIFIED-FILES.txt';
/** Dissimilarity (%) at or above which a changed file counts as replaced, not modified. */
export const REWRITE_THRESHOLD = 90;

const LIST_HEADER = `# Upstream LumiBase files modified by the HeoPress project.
#
# Apache License 2.0, section 4(b): these files were changed by the HeoPress
# project relative to LumiBase commit ${UPSTREAM_BASE}.
# Files that can hold a comment carry the notice in the file itself:
#   ${NOTICE_MARKER}
# The files below cannot hold a comment, so the notice is given here.
# Generated by: node scripts/check-modification-notices.mjs --fix
`;

/** Comment syntax by file kind; null means "cannot hold a comment". */
function commentStyle(file) {
  const base = path.basename(file);
  const lower = base.toLowerCase();
  if (/^dockerfile/i.test(base) || lower === 'caddyfile') return { open: '# ', close: '' };
  if (['.gitignore', '_gitignore', '.dockerignore', '.gitmodules', '.npmrc', '.env.example'].includes(lower)) {
    return { open: '# ', close: '' };
  }
  // Templates are read raw by the scaffolder and its tests (e.g. JSON.parse on
  // package.json.hbs), so they get the notice through the list instead.
  if (lower.endsWith('.hbs')) return null;
  // pnpm rewrites its lockfile and drops comments, so it is listed instead.
  if (lower === 'pnpm-lock.yaml') return null;
  // Generated migrations belong to drizzle-kit and are hashed by the migrator;
  // they are listed instead of edited.
  if (/(^|\/)packages\/database\/drizzle\//.test(file)) return null;
  const ext = lower.includes('.') ? lower.slice(lower.lastIndexOf('.')) : '';
  switch (ext) {
    case '.ts': case '.tsx': case '.mts': case '.cts':
    case '.js': case '.jsx': case '.mjs': case '.cjs': case '.rs':
      return { open: '// ', close: '' };
    case '.css': case '.scss':
      return { open: '/* ', close: ' */' };
    case '.yml': case '.yaml': case '.toml': case '.sh': case '.bash': case '.py':
    case '.example': case '.service': case '.timer': case '.conf': case '.env':
      return { open: '# ', close: '' };
    case '.sql':
      return { open: '-- ', close: '' };
    case '.html': case '.xml': case '.svg':
      return { open: '<!-- ', close: ' -->' };
    default:
      return null;
  }
}

function git(root, args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });
}

/** Upstream files changed since `base`, as { path, upstreamPath }. Pure moves are not modifications. */
export function modifiedUpstreamFiles(root, base) {
  try {
    git(root, ['cat-file', '-e', `${base}^{commit}`]);
  } catch {
    throw new Error(`upstream base ${base} is not in this clone; fetch full history (e.g. actions/checkout fetch-depth: 0)`);
  }
  // -B breaks complete rewrites so they are not reported as edits of the upstream file.
  const out = git(root, ['diff', '--name-status', '-B', '-M', '-l0', base, '--']).trim();
  const files = [];
  const lines = out ? out.split('\n') : [];
  const deleted = new Set(lines.filter((l) => l.startsWith('D\t')).map((l) => l.split('\t')[1]));
  for (const line of lines) {
    const parts = line.split('\t');
    const kind = parts[0][0];
    if (kind === 'A') {
      // Small files that were renamed *and* heavily edited fall below git's
      // similarity threshold and show up as delete + add. Pair them by path.
      const upstreamPath = upstreamPathFor(parts[1]);
      if (upstreamPath !== parts[1] && deleted.has(upstreamPath)) {
        files.push({ path: parts[1], upstreamPath });
      }
      continue;
    }
    const score = Number(parts[0].slice(1) || 'NaN');
    if (kind === 'M') {
      // "M<score>" is a broken pair: <score>% of the file changed. A (near) total
      // rewrite is a new HeoPress file that took over the path, not a modification.
      if (!Number.isNaN(score) && score >= REWRITE_THRESHOLD) continue;
      files.push({ path: parts[1], upstreamPath: parts[1] });
    } else if ((kind === 'R' || kind === 'C') && score < 100) {
      files.push({ path: parts[2], upstreamPath: parts[1] });
    }
  }
  return files.filter((f) => fs.existsSync(path.join(root, f.path)));
}

/** Reverse of the P01 rebrand applied to a path (heopress -> lumibase). */
export function upstreamPathFor(file) {
  return file
    .replace(/HeoPress/g, 'Lumibase')
    .replace(/HEOPRESS/g, 'LUMIBASE')
    .replace(/heopress/g, 'lumibase');
}

function isBinary(buf) {
  return buf.includes(0);
}

/** Index where the notice line may be inserted without breaking a required first line. */
function insertionIndex(lines, file) {
  let i = 0;
  if (lines[0]?.startsWith('#!')) i = 1;
  const base = path.basename(file).toLowerCase();
  if (/^dockerfile/.test(base)) {
    while (i < lines.length && /^#\s*(syntax|escape|check)\s*=/i.test(lines[i])) i += 1;
  }
  if (/^<!doctype/i.test(lines[i] ?? '') || /^<\?xml/i.test(lines[i] ?? '')) i += 1;
  if (/\.(css|scss)$/.test(base) && /^@charset/i.test(lines[i] ?? '')) i += 1;
  return i;
}

export function addNotice(text, file) {
  const style = commentStyle(file);
  if (!style) return text;
  const lines = text.split('\n');
  const at = insertionIndex(lines, file);
  lines.splice(at, 0, `${style.open}${NOTICE_MARKER}${style.close}`);
  return lines.join('\n');
}

/** Copyright notices: "©", or "Copyright" followed by a year, "{year}"-style template or "(c)". */
const COPYRIGHT_NOTICE = /©|copyright\s*(\(c\)|©)?\s*(\d{4}|\{|\$\{)/i;

function copyrightLines(text) {
  return text.split('\n').map((l) => l.trim()).filter((l) => COPYRIGHT_NOTICE.test(l));
}

export function checkNotices({ root, base = UPSTREAM_BASE, fix = false }) {
  const problems = [];
  const listed = [];
  for (const file of modifiedUpstreamFiles(root, base)) {
    const abs = path.join(root, file.path);
    const buf = fs.readFileSync(abs);
    const style = isBinary(buf) ? null : commentStyle(file.path);
    let text = isBinary(buf) ? '' : buf.toString('utf8');

    if (!isBinary(buf)) {
      let upstream = '';
      try {
        upstream = git(root, ['show', `${base}:${file.upstreamPath}`]);
      } catch {
        upstream = '';
      }
      for (const line of copyrightLines(upstream)) {
        if (!text.includes(line)) problems.push(`${file.path}: upstream copyright line removed: "${line}"`);
      }
    }

    if (style) {
      if (!text.includes(NOTICE_MARKER)) {
        if (fix) {
          text = addNotice(text, file.path);
          fs.writeFileSync(abs, text);
        } else {
          problems.push(`${file.path}: modified upstream file lacks the HeoPress modification notice`);
        }
      }
    } else {
      listed.push(file.path);
    }
  }

  listed.sort();
  const expectedList = `${LIST_HEADER}${listed.join('\n')}\n`;
  const listPath = path.join(root, MODIFIED_LIST);
  const currentList = fs.existsSync(listPath) ? fs.readFileSync(listPath, 'utf8') : null;
  if (currentList !== expectedList) {
    if (fix) {
      fs.mkdirSync(path.dirname(listPath), { recursive: true });
      fs.writeFileSync(listPath, expectedList);
    } else {
      problems.push(`${MODIFIED_LIST} is out of date; run node scripts/check-modification-notices.mjs --fix`);
    }
  }
  return problems;
}

function parseArgs(argv) {
  const opts = { root: process.cwd(), base: UPSTREAM_BASE, fix: false };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--fix') opts.fix = true;
    else if (argv[i] === '--root') opts.root = path.resolve(argv[++i]);
    else if (argv[i] === '--base') opts.base = argv[++i];
  }
  return opts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2));
  let problems;
  try {
    problems = checkNotices(opts);
  } catch (err) {
    console.error(`[modification-notices] ${err.message}`);
    process.exit(1);
  }
  if (problems.length > 0) {
    console.error(`[modification-notices] ${problems.length} problem(s):`);
    for (const p of problems) console.error(`  ✖ ${p}`);
    console.error('Fix: node scripts/check-modification-notices.mjs --fix (it never removes copyright lines; restore any it reports).');
    process.exit(1);
  }
  console.log(`[modification-notices] ok${opts.fix ? ' (fixed)' : ''}`);
}
