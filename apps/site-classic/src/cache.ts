import { createHash } from 'node:crypto';
import { and, eq, gt, lte, sql } from 'drizzle-orm';
import { renderCache, siteRenderVersions, type Database } from '@heopress/database';

/**
 * The page cache (HeoPress P06 tasks 3.1–3.3, 7.2; design §4, R8, R9): two levels — this process's LRU
 * (bounded in bytes) and `lumibase_render_cache` (shared by every renderer process) — of rendered
 * answers: 200, 301, 404, 410.
 *
 * The key holds the mode, the site, host, path, the query parameters that change the page (`page`; `q` on
 * the search page), the theme version and the site's render version. The language is not a separate part:
 * every language entry (path prefix, subdomain, own domain) is a host or a path, so host and path decide
 * it (Accept-Language never changes an answer). The mode is always `public`: previews are never cached
 * (they are answered before any lookup), and a key cannot be made for anything else. Every write that changes the site's
 * public output raises that version in its own transaction, and the version is read in the same snapshot
 * as the page data: an answer is never stored under a version newer than its data, and a changed site is
 * never answered from an older version's entry — whether the change events arrive or not.
 */

/**
 * A stored answer (HeoPress P07 task 1.3): status, body, its `content-type` and the representation headers
 * the system generated for it — replayed identically on 200, HEAD and 304 — and an entity tag over all of them.
 */
export interface CachedPage {
  status: number;
  body: string;
  etag: string;
  /** For a 301: the target without the request's query (the request's own query is appended when served). */
  location: string | null;
  contentType: string;
  /** Representation headers, lowercase names from `REPRESENTATION_HEADERS`, validated values. */
  headers: Record<string, string>;
  /** Read from the shared level: when its row expires (ms) — this process keeps it no longer. */
  expiresAt?: number;
}

export const HTML_TYPE = 'text/html; charset=utf-8';

/**
 * The response headers an answer may carry from the cache: generated by the system, never named by content.
 * Anything else is refused when the answer is made.
 */
export const REPRESENTATION_HEADERS: ReadonlySet<string> = new Set([
  'x-robots-tag',
  'link',
  'content-signal',
  'content-language',
  // A site's root file (P07 task 3.8): never sniffed as another type, and a sandbox when opened as a document.
  'x-content-type-options',
  'content-security-policy',
]);

/** RFC 9110 §5.6.2 token. */
const TOKEN = /^[!#$%&'*+.^_`|~0-9A-Za-z-]+$/;
/** A field value: visible ASCII and spaces, not only whitespace (no CR / LF / other controls, no non-ASCII). */
const FIELD_VALUE = /^[\x20-\x7e]*[\x21-\x7e][\x20-\x7e]*$/;

/** The validated representation headers (lowercase names, sorted), or an error naming the first bad one. */
export function representationHeaders(input: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const name of Object.keys(input).sort()) {
    const lower = name.toLowerCase();
    if (!TOKEN.test(name) || !REPRESENTATION_HEADERS.has(lower)) throw new Error(`response header not allowed: ${JSON.stringify(name)}`);
    const value = input[name]!;
    if (typeof value !== 'string' || !FIELD_VALUE.test(value)) throw new Error(`response header value not allowed for ${lower}`);
    out[lower] = value;
  }
  return out;
}

/**
 * A redirect target (the `location` header): visible ASCII without spaces or backslashes, well-formed percent
 * escapes, and either a path on this host (one leading `/`, never `//`: that names another host) or an
 * absolute `https:` URL with a host.
 */
export function isRedirectTarget(s: string): boolean {
  if (typeof s !== 'string' || !FIELD_VALUE.test(s) || /[\s\\]/.test(s) || /%(?![0-9A-Fa-f]{2})/.test(s)) return false;
  if (s.startsWith('/')) return !s.startsWith('//');
  if (!s.startsWith('https://')) return false;
  try {
    return new URL(s).hostname !== '';
  } catch {
    return false;
  }
}

/**
 * The `location` of a served redirect: the stored target and the request's own query, the query's bytes that
 * cannot stand in a header percent-encoded (order and repeated parameters kept) — after the target's own query
 * (`&`), before its fragment. Null when the result is not a valid target (never, for a target `cachedPage` accepted).
 */
export function redirectLocation(target: string, query: string): string | null {
  let q: string;
  try {
    q = query.replace(/[^\x21-\x7e]|\\|%(?![0-9A-Fa-f]{2})/gu, (ch) => encodeURIComponent(ch));
  } catch {
    return null; // a lone surrogate: nothing to encode it as
  }
  const hash = target.indexOf('#');
  const [base, fragment] = hash >= 0 ? [target.slice(0, hash), target.slice(hash)] : [target, ''];
  // No separator only after an empty query (`/x?`) or a trailing `&`; a `?` inside a query is data.
  const queryAt = base.indexOf('?');
  const separator = queryAt < 0 ? '?' : queryAt === base.length - 1 || base.endsWith('&') ? '' : '&';
  const out = q ? `${base}${separator}${q}${fragment}` : target;
  return isRedirectTarget(out) ? out : null;
}

/** A content-type: `type/subtype` with optional parameters, under the same field-value rules. */
const CONTENT_TYPE = /^[!#$%&'*+.^_`|~0-9A-Za-z-]+\/[!#$%&'*+.^_`|~0-9A-Za-z-]+( *; *[!#$%&'*+.^_`|~0-9A-Za-z-]+=[!#$%&'*+.^_`|~0-9A-Za-z-]+)*$/;


/** An answer to cache and serve: validated, with its entity tag. */
export function cachedPage(
  status: number,
  body: string,
  location: string | null,
  opts: { contentType?: string; headers?: Record<string, string> } = {},
): CachedPage {
  if (!Number.isInteger(status) || status < 100 || status > 599) throw new Error(`status not allowed: ${status}`);
  if (typeof body !== 'string') throw new Error('body must be a string');
  // A target exactly on a redirect (`isRedirectTarget`).
  if (status === 301) {
    if (typeof location !== 'string' || !isRedirectTarget(location)) throw new Error('location not allowed');
  } else if (location !== null) {
    throw new Error('location not allowed without a redirect');
  }
  const contentType = opts.contentType ?? HTML_TYPE;
  if (typeof contentType !== 'string' || !FIELD_VALUE.test(contentType) || !CONTENT_TYPE.test(contentType)) throw new Error(`content-type not allowed: ${JSON.stringify(contentType)}`);
  const headers = representationHeaders(opts.headers ?? {});
  return { status, body, location, contentType, headers, etag: etagOf(status, body, location, contentType, headers) };
}

export interface CacheKeyInput {
  mode: 'public';
  siteId: string;
  host: string;
  path: string;
  query: URLSearchParams;
  themeVersion: string;
  siteVersion: number;
}

/** How long a level-2 entry is kept at most (versions make it stale sooner). */
const L2_TTL_MS = 24 * 60 * 60 * 1000;
/**
 * The format of the public output (pages, discovery files, their headers). Part of every cache key: an
 * update that changes what is generated raises it, and no entry of the former format is served again.
 * `apps/site-classic/output-contract.json` holds the digest of the sample output of each version (a test
 * fails when the output changes and this does not). The sample covers the theme's output and what the service
 * generates around it: list and language-home canonicals, the head of each kind of page (from version 4).
 */
export const OUTPUT_VERSION = 18;
/** The fleet-wide sweep lock (an arbitrary constant: "render cache"). */
const SWEEP_LOCK = 0x72656e64;
/**
 * Largest answer the shared level stores, by type: a page is bounded by the engine's output limit; discovery
 * files (sitemaps, feeds, llms-full) may be larger. Larger answers stay in this process only.
 */
function sharedLimit(contentType: string): number {
  return mediaType(contentType) === 'text/html' ? 2_000_000 : 8_000_000;
}

/** The media type without parameters, lowercase (media types are case-insensitive). */
function mediaType(contentType: string): string {
  return contentType.split(';', 1)[0]!.trim().toLowerCase();
}

/** The bytes an answer takes in the shared level: the UTF-8 body, its target, type and headers. */
export function storedBytes(page: CachedPage): number {
  const head = Object.entries(page.headers).reduce((n, [k, v]) => n + Buffer.byteLength(k) + Buffer.byteLength(v) + 4, 0);
  return Buffer.byteLength(page.body, 'utf8') + Buffer.byteLength(page.location ?? '') + Buffer.byteLength(page.contentType) + head;
}

/**
 * The query parameters that change the answer, normalised (R9): `page` (its first value; anything but a
 * small number collapses to one "invalid" entry: a 404) and, on the search page, `q` (first value,
 * trimmed, at most 200 characters, the renderer's own limit). Everything else changes nothing and is left
 * out, so it cannot multiply entries.
 */
/** Whether the path may be a search page: its last segment, percent-decoded, is `search` (`/%73earch/` too). */
function maybeSearch(path: string): boolean {
  const segments = path.split('/').filter(Boolean);
  const last = segments[segments.length - 1];
  if (last === undefined) return false;
  try {
    return decodeURIComponent(last) === 'search';
  } catch {
    return false;
  }
}

export function cacheQuery(path: string, query: URLSearchParams): string {
  const parts: string[] = [];
  const page = query.get('page');
  if (page !== null) parts.push(`page=${/^[1-9]\d{0,5}$/.test(page) ? page : 'invalid'}`);
  if (maybeSearch(path)) {
    const q = (query.get('q') ?? '').trim().slice(0, 200);
    if (q) parts.push(`q=${encodeURIComponent(q)}`);
  }
  return parts.join('&');
}

export function cacheKey(k: CacheKeyInput): string {
  if (k.mode !== 'public') throw new Error('only public answers are cached');
  const raw = [`o${OUTPUT_VERSION}`, k.mode, k.siteId, k.host, k.path, cacheQuery(k.path, k.query), k.themeVersion, String(k.siteVersion)].join('\u0000');
  return createHash('sha256').update(raw).digest('hex');
}

/** A weak validator of the answer: its bytes, status, target, type and representation headers. */
export function etagOf(status: number, body: string, location: string | null, contentType = HTML_TYPE, headers: Record<string, string> = {}): string {
  const head = Object.keys(headers)
    .sort()
    .map((k) => `${k}:${headers[k]}`)
    .join('\n');
  return `W/"${createHash('sha256').update(`${status}\u0000${location ?? ''}\u0000${contentType}\u0000${head}\u0000${body}`).digest('base64url').slice(0, 32)}"`;
}

/** Whether `If-None-Match` names this entity tag (weak comparison, RFC 9110 §13.1.2). */
export function matchesEtag(header: string | undefined, etag: string): boolean {
  if (!header) return false;
  if (header.trim() === '*') return true;
  const bare = (t: string) => t.trim().replace(/^W\//, '');
  return header.split(',').some((t) => bare(t) === bare(etag));
}

/**
 * The sites in sweep order: after the one the last pass stopped at (by its position in the list, or by
 * byte order when it has since left the list), wrapping around — every site gets its turn.
 */
export function rotation(sites: string[], cursor: string): string[] {
  if (sites.length === 0) return [];
  const at = sites.indexOf(cursor);
  const start = at >= 0 ? (at + 1) % sites.length : sites.findIndex((s) => Buffer.compare(Buffer.from(s), Buffer.from(cursor)) > 0);
  return start <= 0 ? sites : [...sites.slice(start), ...sites.slice(0, start)];
}

export class PageCache {
  private readonly l1 = new Map<string, { page: CachedPage; bytes: number; expiresAt: number | null }>();
  private bytes = 0;
  private readonly now: () => number;

  constructor(
    private readonly db: Database,
    private readonly opts: { maxBytes: number; now?: () => number } = { maxBytes: 64 * 1024 * 1024 },
  ) {
    this.now = opts.now ?? Date.now;
  }

  /** This process's copy, refreshed as most recently used; none once it expired (an answer that depends on the time). */
  local(key: string): CachedPage | null {
    const hit = this.l1.get(key);
    if (!hit) return null;
    this.l1.delete(key);
    if (hit.expiresAt !== null && hit.expiresAt <= this.now()) {
      this.bytes -= hit.bytes;
      return null;
    }
    this.l1.set(key, hit);
    return hit.page;
  }

  /** `expiresAt` (ms): when the answer stops being true whatever the site's version (the news sitemap's 48-hour window). */
  remember(key: string, page: CachedPage, expiresAt: number | null = null): void {
    const head = Object.entries(page.headers).reduce((n, [k, v]) => n + k.length + v.length, 0);
    const bytes = (page.body.length + (page.location?.length ?? 0) + page.contentType.length + head) * 2 + 200;
    if (bytes > this.opts.maxBytes / 8) return;
    const old = this.l1.get(key);
    if (old) {
      this.l1.delete(key);
      this.bytes -= old.bytes;
    }
    this.l1.set(key, { page, bytes, expiresAt });
    this.bytes += bytes;
    for (const [k, v] of this.l1) {
      if (this.bytes <= this.opts.maxBytes) break;
      this.l1.delete(k);
      this.bytes -= v.bytes;
    }
  }

  /**
   * Store an answer: always in this process (bounded in bytes); in level 2 only what is bounded by the
   * site's content — content pages (200) and deleted pages (410) — never what any path or query can
   * produce (404s, alias redirects, search results), so requests cannot grow the table (R9).
   * Level 2 in its own short transaction; a failure only costs a later miss.
   */
  async store(key: string, siteId: string, siteVersion: number, page: CachedPage, opts: { shared: boolean; expiresAt?: number | null }): Promise<void> {
    const expiresAt = opts.expiresAt ?? null;
    this.remember(key, page, expiresAt);
    if (!opts.shared || (page.status !== 200 && page.status !== 410) || storedBytes(page) > sharedLimit(page.contentType)) return;
    try {
      await this.db.transaction(async (tx) => {
        await tx.execute(sql`SELECT set_config('app.site_id', ${siteId}, true)`);
        await tx
          .insert(renderCache)
          .values({
            key,
            siteId,
            siteVersion,
            status: page.status,
            body: page.body,
            etag: page.etag,
            location: page.location,
            contentType: page.contentType,
            headers: page.headers,
            expiresAt: new Date(Math.min(this.now() + L2_TTL_MS, expiresAt ?? Infinity)),
          })
          // The same key's row stays (another process stored the same answer) — unless it expired (an answer that depends
          // on the time, P07 task 3.7): then this one takes its place, before the sweep removes it.
          .onConflictDoUpdate({
            target: renderCache.key,
            set: { siteVersion, status: page.status, body: page.body, etag: page.etag, location: page.location, contentType: page.contentType, headers: page.headers, expiresAt: sql`excluded.expires_at` },
            setWhere: lte(renderCache.expiresAt, new Date(this.now())),
          });
      });
    } catch (err) {
      console.error('[site-classic] page cache write failed', err instanceof Error ? err.message : err);
    }
  }

  private sweeping = false;
  /** Where the last sweep stopped: the next one starts after this site (every site gets its turn). */
  private cursor = '';

  /**
   * Delete level-2 entries that expired or belong to an older render version of their site, in bounded
   * batches. One sweep at a time in this process, and in the whole fleet (an advisory lock); each site's
   * version read in that site's scope (the optional row-level security). Returns rows deleted.
   */
  async sweep(opts: { batch?: number; maxBatches?: number; maxSites?: number } = {}): Promise<number> {
    if (this.sweeping) return 0;
    this.sweeping = true;
    const batch = opts.batch ?? 1000;
    let budget = opts.maxBatches ?? 50;
    let deleted = 0;
    try {
      return await this.db.transaction(async (tx) => {
        const count = async (q: ReturnType<typeof sql>) => Number(((await tx.execute(q)) as unknown as Array<{ n: number }>)[0]?.n ?? 0);
        const [lock] = (await tx.execute(sql`SELECT pg_try_advisory_xact_lock(${SWEEP_LOCK}) AS ok`)) as unknown as Array<{ ok: boolean }>;
        if (!lock?.ok) return 0;
        /** Delete in batches while there is something to delete; only batches that deleted rows spend the budget. */
        const drain = async (q: (limit: number) => ReturnType<typeof sql>) => {
          while (budget > 0) {
            const n = await count(q(batch));
            deleted += n;
            if (n === 0) return;
            budget--;
            if (n < batch) return;
          }
        };
        // Expired entries: indexed by expiry, no version needed.
        await drain((limit) => sql`WITH d AS (DELETE FROM ${renderCache} WHERE ${renderCache.key} IN (SELECT ${renderCache.key} FROM ${renderCache} WHERE ${renderCache.expiresAt} < now() LIMIT ${limit}) RETURNING 1) SELECT count(*)::int AS n FROM d`);
        // Superseded entries, site by site in its scope, starting after where the last sweep stopped.
        // Byte order on both sides (the database's collation could disagree with JavaScript's comparison).
        const all = ((await tx.execute(sql`SELECT DISTINCT ${renderCache.siteId} COLLATE "C" AS site FROM ${renderCache} ORDER BY 1`)) as unknown as Array<{ site: string }>).map((r) => r.site);
        const order = rotation(all, this.cursor);
        for (const site of order.slice(0, opts.maxSites ?? 200)) {
          if (budget <= 0) break;
          await tx.execute(sql`SELECT set_config('app.site_id', ${site}, true)`);
          const [v] = (await tx.execute(sql`SELECT ${siteRenderVersions.version} AS v FROM ${siteRenderVersions} WHERE ${siteRenderVersions.siteId} = ${site}`)) as unknown as Array<{ v: number }>;
          await drain((limit) => sql`WITH d AS (DELETE FROM ${renderCache} WHERE ${renderCache.key} IN (SELECT ${renderCache.key} FROM ${renderCache} WHERE ${renderCache.siteId} = ${site} AND ${renderCache.siteVersion} < ${v?.v ?? 0} LIMIT ${limit}) RETURNING 1) SELECT count(*)::int AS n FROM d`);
          this.cursor = site;
        }
        return deleted;
      });
    } finally {
      this.sweeping = false;
    }
  }
}

/**
 * A level-2 read inside the request's snapshot (`tx`: the request transaction). The row is checked again as
 * it is read — what the shared level may hold (200 or 410), a valid type, headers and target — and its entity
 * tag recomputed; a row that fails (written by an older or broken writer, or by hand) is a miss.
 */
export async function readStored(tx: Pick<Database, 'select'>, key: string, siteId: string, now: Date = new Date()): Promise<CachedPage | null> {
  const [row] = await tx
    .select({
      status: renderCache.status,
      body: renderCache.body,
      etag: renderCache.etag,
      location: renderCache.location,
      contentType: renderCache.contentType,
      headers: renderCache.headers,
      expiresAt: renderCache.expiresAt,
    })
    .from(renderCache)
    // An expired row is a miss even before the sweep removes it (an answer that depends on the time, P07 task 3.7).
    .where(and(eq(renderCache.key, key), eq(renderCache.siteId, siteId), gt(renderCache.expiresAt, now)));
  if (!row || (row.status !== 200 && row.status !== 410)) return null;
  try {
    const page = cachedPage(row.status, row.body, row.location, { contentType: row.contentType, headers: row.headers });
    return row.expiresAt instanceof Date ? { ...page, expiresAt: row.expiresAt.getTime() } : page;
  } catch {
    return null;
  }
}
